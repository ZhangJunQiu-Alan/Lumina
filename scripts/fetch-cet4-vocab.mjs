import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const APP_URL = 'https://raw.githubusercontent.com/mahavivo/english-wordlists/master/CET4_edited.txt';
const OUTPUT_FILE = path.resolve(process.cwd(), 'src/data/cet4-vocab.ts');

async function fetchText(url) {
  const res = await fetch(url);
  if (!res.ok) {
    throw new Error(`Failed to fetch ${url}: HTTP ${res.status}`);
  }

  return res.text();
}

function extractWords(rawText) {
  const words = [];
  const seen = new Set();

  for (const line of rawText.split('\n')) {
    // Matches words followed by a space and phonetic bracket [ or a part of speech like art., n., vt.
    const match = line.trim().match(/^([a-zA-Z-]+)(?:\s+\[|\s+[a-zA-Z]+\.)/);
    if (match) {
      const word = match[1].toLowerCase();
      if (!seen.has(word)) {
        seen.add(word);
        words.push(word);
      }
    }
  }

  return words;
}

function renderTypeScript(words, sourceUrl) {
  const generatedAt = new Date().toISOString();
  const serialized = JSON.stringify(words, null, 2);

  return `// Generated by scripts/fetch-cet4-vocab.mjs on ${generatedAt}
// Source: ${sourceUrl}

export const CET4_TITLE = '四级大纲核心词汇';

export const CET4_WORDS: string[] = ${serialized};
`;
}

async function main() {
  const rawText = await fetchText(APP_URL);
  const words = extractWords(rawText);

  if (words.length < 4000) {
    throw new Error(
      `Expected around 4600 words, received ${words.length}. Review the upstream vocabulary source before updating local data.`,
    );
  }

  await mkdir(path.dirname(OUTPUT_FILE), { recursive: true });
  await writeFile(OUTPUT_FILE, renderTypeScript(words, APP_URL), 'utf8');

  console.log(`Wrote ${words.length} unique words to ${OUTPUT_FILE}`);
  console.log(`First few samples: ${words.slice(0, 10).join(', ')}`);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
