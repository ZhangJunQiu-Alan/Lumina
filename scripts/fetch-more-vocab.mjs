import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

async function fetchText(url) {
  const res = await fetch(url);
  if (!res.ok) {
    throw new Error(`Failed to fetch ${url}: HTTP ${res.status}`);
  }
  return res.text();
}

function extractWords(rawText, filterFn) {
  const words = [];
  const seen = new Set();
  
  for (const line of rawText.split('\n')) {
    const trimmed = line.trim();
    if (!trimmed) continue;
    
    // Updated regex to handle line numbers, optional asterisk, and optional phonetic bracket or part-of-speech
    // Matches patterns like: "1. abandon [", "2. *abacus [", "*abase [", "a, an ["
    const match = trimmed.match(/^(?:\d+\.\s+)?(\*?)([a-zA-Z\-]+).*?(?:\s+\[|\s+[a-zA-Z]+\.)/);
    if (match) {
      const isStarred = match[1] === '*';
      const word = match[2].toLowerCase();
      
      if (filterFn && !filterFn(isStarred)) continue;

      if (!seen.has(word)) {
        seen.add(word);
        words.push(word);
      }
    }
  }
  
  return words;
}

function renderTypeScript(words, sourceUrl, title, constName) {
  const generatedAt = new Date().toISOString();
  const serialized = JSON.stringify(words, null, 2);

  return `// Generated by scripts/fetch-more-vocab.mjs on ${generatedAt}
// Source: ${sourceUrl}

export const ${constName}_TITLE = '${title}';

export const ${constName}_WORDS: string[] = ${serialized};
`;
}

async function processVocab(url, fileName, title, constName, filterFn = null) {
  const OUTPUT_FILE = path.resolve(process.cwd(), `src/data/${fileName}`);
  const rawText = await fetchText(url);
  const words = extractWords(rawText, filterFn);

  await mkdir(path.dirname(OUTPUT_FILE), { recursive: true });
  await writeFile(OUTPUT_FILE, renderTypeScript(words, url, title, constName), 'utf8');

  console.log(`Wrote ${words.length} unique words to ${OUTPUT_FILE} (${title})`);
  return words.length;
}

async function main() {
  const baseUrl = 'https://raw.githubusercontent.com/mahavivo/english-wordlists/master';
  
  // CET6
  await processVocab(
    `${baseUrl}/CET6_edited.txt`,
    'cet6-vocab.ts',
    '六级大纲核心词汇',
    'CET6'
  );

  // NPEE (考研)
  await processVocab(
    `${baseUrl}/NPEE_Wordlist.txt`,
    'npee-vocab.ts',
    '考研英语大纲词汇',
    'NPEE'
  );

  // TEM4 (专四) - Filter out starred from the combined table
  await processVocab(
    `${baseUrl}/%E8%8B%B1%E8%AF%AD%E4%B8%93%E4%B8%9A%E5%9B%9B%E5%85%AB%E7%BA%A7%E8%AF%8D%E6%B1%87%E8%A1%A8.txt`,
    'tem4-vocab.ts',
    '英语专业四级(TEM4)',
    'TEM4',
    (isStarred) => !isStarred
  );

  // TEM8 (专八) - Only specific starred ones
  await processVocab(
    `${baseUrl}/%E8%8B%B1%E8%AF%AD%E4%B8%93%E4%B8%9A%E6%98%9F%E6%A0%87%E5%85%AB%E7%BA%A7%E8%AF%8D%E6%B1%87.txt`,
    'tem8-vocab.ts',
    '英语专业八级(TEM8)',
    'TEM8'
  );
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
