import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const SOURCE_URL = 'https://raw.githubusercontent.com/mahavivo/english-wordlists/master/Highschool_edited.txt';
const OUTPUT_FILE = path.resolve(process.cwd(), 'src/data/gaokao-vocab.ts');

async function fetchText(url) {
  const res = await fetch(url);
  if (!res.ok) {
    throw new Error(`Failed to fetch ${url}: HTTP ${res.status}`);
  }

  return res.text();
}

function extractWords(rawText) {
  const words = [];
  const seen = new Set();

  for (const line of rawText.split('\n')) {
    const value = line.trim().replace(/\s+/g, ' ');
    if (!value) continue;

    const word = value.toLowerCase();
    if (!seen.has(word)) {
      seen.add(word);
      words.push(word);
    }
  }

  return words;
}

function renderTypeScript(words, sourceUrl) {
  const generatedAt = new Date().toISOString();
  const serialized = JSON.stringify(words, null, 2);

  return `// Generated by scripts/fetch-gaokao-vocab.mjs on ${generatedAt}
// Source: ${sourceUrl}

export const GAOKAO_TITLE = '高考英语核心词汇';

export const GAOKAO_WORDS: string[] = ${serialized};
`;
}

async function main() {
  const rawText = await fetchText(SOURCE_URL);
  const words = extractWords(rawText);

  if (words.length < 3000) {
    throw new Error(
      `Expected at least 3000 words, received ${words.length}. Review the upstream vocabulary source before updating local data.`,
    );
  }

  await mkdir(path.dirname(OUTPUT_FILE), { recursive: true });
  await writeFile(OUTPUT_FILE, renderTypeScript(words, SOURCE_URL), 'utf8');

  console.log(`Wrote ${words.length} unique words to ${OUTPUT_FILE}`);
  console.log(`First few samples: ${words.slice(0, 10).join(', ')}`);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
