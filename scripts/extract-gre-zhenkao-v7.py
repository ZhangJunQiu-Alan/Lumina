#!/usr/bin/env python3

from __future__ import annotations

import argparse
import difflib
import importlib.util
import re
import sys
from pathlib import Path

EXPECTED_WORD_COUNT = 1351
DEFAULT_INPUT = Path('GRE镇考机经词7.0-正序（2026年版）.pdf')
DEFAULT_OUTPUT = Path('src/data/gre-zhenkao-v7.ts')
WORD_PATTERN = re.compile(r"^([A-Za-z][A-Za-z'’\- ]*[A-Za-z])\s+\[[^\]]+\]")


def require_pdf_support() -> None:
    missing = []
    for module_name in ('pypdf', 'cryptography'):
        if importlib.util.find_spec(module_name) is None:
            missing.append(module_name)

    if missing:
        joined = ', '.join(missing)
        raise SystemExit(
            f'Missing Python dependencies: {joined}. Install them before extracting the GRE PDF.',
        )


def normalize_word(raw: str) -> str:
    return re.sub(r'\s+', ' ', raw.replace('’', "'")).strip()


def extract_words(pdf_path: Path) -> list[str]:
    from pypdf import PdfReader

    reader = PdfReader(str(pdf_path))
    words: list[str] = []
    seen: set[str] = set()

    for page in reader.pages:
        text = page.extract_text() or ''
        for raw_line in text.splitlines():
            match = WORD_PATTERN.match(raw_line.strip())
            if not match:
                continue

            word = normalize_word(match.group(1))
            key = word.lower()
            if key in seen:
                continue

            seen.add(key)
            words.append(word)

    if len(words) != EXPECTED_WORD_COUNT:
        raise SystemExit(
            f'Expected {EXPECTED_WORD_COUNT} GRE words, extracted {len(words)}. Review the parser before updating data.',
        )

    return words


def render_module(words: list[str], input_path: Path) -> str:
    payload = '\n'.join(words)

    return f"""// Generated by scripts/extract-gre-zhenkao-v7.py
// Source: {input_path.name}

export const GRE_ZHENKAO_V7_TITLE = 'GRE镇考机经词 7.0';

export const GRE_ZHENKAO_V7_WORDS: string[] = `
{payload}
`.trim().split('\\n');
"""


def main() -> None:
    parser = argparse.ArgumentParser(description='Extract GRE 镇考机经词 7.0 headwords from the official PDF.')
    parser.add_argument('--input', type=Path, default=DEFAULT_INPUT)
    parser.add_argument('--output', type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument('--stdout', action='store_true', help='Print the generated TypeScript module to stdout.')
    parser.add_argument('--check', action='store_true', help='Fail if the generated module differs from the checked-in file.')
    args = parser.parse_args()

    require_pdf_support()

    if not args.input.exists():
        raise SystemExit(f'Input PDF not found: {args.input}')

    words = extract_words(args.input)
    module_text = render_module(words, args.input)

    if args.stdout:
        sys.stdout.write(module_text)
        return

    if args.check:
        if not args.output.exists():
            raise SystemExit(f'Output file missing: {args.output}')

        current = args.output.read_text(encoding='utf-8')
        if current != module_text:
            diff = ''.join(difflib.unified_diff(
                current.splitlines(keepends=True),
                module_text.splitlines(keepends=True),
                fromfile=str(args.output),
                tofile='generated',
            ))
            sys.stdout.write(diff)
            raise SystemExit(1)

        print(f'GRE word list is up to date: {args.output}')
        return

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(module_text, encoding='utf-8')
    print(f'Wrote {len(words)} GRE words to {args.output}')


if __name__ == '__main__':
    main()
