import { mkdtemp, mkdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { tmpdir } from 'node:os';
import { pathToFileURL } from 'node:url';

const APP_URL = 'https://hefengxian.github.io/my-ielts/';
const OUTPUT_FILE = path.resolve(process.cwd(), 'src/data/ielts-vocab.ts');
const EXPECTED_CHAPTER_COUNT = 22;
const EXPECTED_WORD_COUNT = 3674;

async function fetchText(url) {
  const res = await fetch(url);
  if (!res.ok) {
    throw new Error(`Failed to fetch ${url}: HTTP ${res.status}`);
  }

  return res.text();
}

function extractEntryBundleUrl(indexHtml) {
  const match = indexHtml.match(/<script type="module" crossorigin src="([^"]+assets\/index-[^"]+\.js)"><\/script>/);
  if (!match) {
    throw new Error('Could not find the Vite entry bundle in the index HTML.');
  }

  return new URL(match[1], APP_URL).href;
}

function extractVocabularyChunkUrl(entryBundle, entryBundleUrl) {
  const match = entryBundle.match(/import\("(\.\/vocabulary-[^"]+\.js)"\)/);
  if (!match) {
    throw new Error('Could not find the vocabulary chunk path in the entry bundle.');
  }

  return new URL(match[1], entryBundleUrl).href;
}

function extractChapterTitle(label, fallbackKey) {
  const source = label || fallbackKey;
  const match = source.match(/^\d+_(.+)$/);
  return (match?.[1] ?? source).trim();
}

function normalizeWord(entry) {
  if (!entry || !Array.isArray(entry.word) || entry.word.length === 0) {
    throw new Error(`Invalid word entry encountered: ${JSON.stringify(entry)}`);
  }

  const primary = String(entry.word[0] ?? '').trim();
  if (!primary) {
    throw new Error(`Encountered an empty primary spelling: ${JSON.stringify(entry)}`);
  }

  return primary;
}

function normalizeChapters(rawVocabulary) {
  const entries = Object.entries(rawVocabulary);

  return entries.map(([key, chapter], index) => ({
    id: index + 1,
    title: extractChapterTitle(chapter.label, key),
    words: chapter.words.flat().map(normalizeWord),
  }));
}

function renderTypeScript(chapters, sourceUrl) {
  const generatedAt = new Date().toISOString();
  const serialized = JSON.stringify(chapters, null, 2);

  return `// Generated by scripts/fetch-ielts-vocab.mjs on ${generatedAt}
// Source: ${sourceUrl}

export interface IELTSChapter {
  id: number;
  title: string;
  words: string[];
}

export const IELTS_CHAPTERS: IELTSChapter[] = ${serialized};

export const IELTS_WORDS_FLAT: string[] = IELTS_CHAPTERS.flatMap((chapter) => chapter.words);
`;
}

async function loadRemoteVocabularyModule(vocabularyChunkUrl) {
  const tempDir = await mkdtemp(path.join(tmpdir(), 'ielts-vocab-'));
  const tempFile = path.join(tempDir, 'vocabulary.mjs');

  try {
    const chunkCode = await fetchText(vocabularyChunkUrl);
    await writeFile(tempFile, chunkCode, 'utf8');

    const moduleUrl = `${pathToFileURL(tempFile).href}?t=${Date.now()}`;
    const imported = await import(moduleUrl);
    return imported.default;
  } finally {
    await rm(tempDir, { recursive: true, force: true });
  }
}

async function main() {
  const indexHtml = await fetchText(APP_URL);
  const entryBundleUrl = extractEntryBundleUrl(indexHtml);
  const entryBundle = await fetchText(entryBundleUrl);
  const vocabularyChunkUrl = extractVocabularyChunkUrl(entryBundle, entryBundleUrl);
  const rawVocabulary = await loadRemoteVocabularyModule(vocabularyChunkUrl);

  const chapters = normalizeChapters(rawVocabulary);
  const totalWords = chapters.reduce((sum, chapter) => sum + chapter.words.length, 0);

  if (chapters.length !== EXPECTED_CHAPTER_COUNT) {
    throw new Error(
      `Expected ${EXPECTED_CHAPTER_COUNT} chapters, received ${chapters.length}. Review the upstream vocabulary source before updating local data.`,
    );
  }

  if (totalWords !== EXPECTED_WORD_COUNT) {
    throw new Error(
      `Expected ${EXPECTED_WORD_COUNT} words, received ${totalWords}. Review the upstream vocabulary source before updating local data.`,
    );
  }

  await mkdir(path.dirname(OUTPUT_FILE), { recursive: true });
  await writeFile(OUTPUT_FILE, renderTypeScript(chapters, vocabularyChunkUrl), 'utf8');

  console.log(`Wrote ${chapters.length} chapters and ${totalWords} words to ${OUTPUT_FILE}`);
  console.log(`First chapter sample: ${chapters[0].words.slice(0, 3).join(', ')}`);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
